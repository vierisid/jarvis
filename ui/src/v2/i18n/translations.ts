export const TRANSLATIONS: Record<DashboardLocale, Messages> = { en, es };

export function normalizeDashboardLocale(value: unknown): DashboardLocale {
  if (typeof value !== "string") return "en";
  return value.trim().toLowerCase().split(/[-_]/, 1)[0] === "es" ? "es" : "en";
}

export function translate(
  locale: DashboardLocale,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const template = TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}
