/**
 * The hosted shared pieces tree (#971): what scripts/build-shared-runtime.ts
 * installs, and the license gate it must pass before anything in it runs.
 * scripts/check-piece-licenses.ts runs the same install and the same gate in
 * the weekly catalog sync and on PRs that change the tree (test.yml), so a
 * violation shows up there before the next hosted build would fail on it.
 */

import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import type { CatalogEntry } from "./catalog";
import { describeViolations, renderNotices, scanInstalledTree, type LicenseScan } from "./license-scan";

/** The Activepieces monorepo license, vendored with its source (MIT outside /ee/). */
const ACTIVEPIECES_LICENSE = resolve(import.meta.dir, "../activepieces/LICENSE.activepieces");

/** The package.json the shared tree is installed from: one dependency per piece, at its catalog range. */
export function sharedPiecesPackageJson(catalog: readonly CatalogEntry[]): string {
  const deps: Record<string, string> = {};
  for (const entry of catalog) deps[entry.npmPackage] = entry.versionRange;
  return (
    JSON.stringify(
      {
        name: "jarvis-shared-pieces",
        private: true,
        description: "Shared community-pieces catalog (generated by build-shared-runtime)",
        dependencies: deps,
      },
      null,
      2,
    ) + "\n"
  );
}

export interface SharedTreeLicenseCheck {
  /** False when any package is denied or the tree could not be read in full. */
  ok: boolean;
  /** One line per denied package (with the chain that installed it) and per unreadable entry. */
  problems: string[];
  /**
   * The generated notices, rendered from the tree as scanned; null when the
   * tree fails, because it is not going to ship. The caller writes them.
   */
  notices: string | null;
  /** Reviewed-list entries nothing in this tree used: candidates for removal. */
  unusedReviewed: string[];
  /** Distinct releases (`name@version`) in the tree. */
  packages: number;
  weakCopyleft: string[];
  reviewed: string[];
  scan: LicenseScan;
}

/**
 * One printable line: no control characters and no `::`, which the Actions
 * runner reads as a workflow command. License text in a problem line is
 * whatever the package.json held.
 */
export function oneLine(s: string): string {
  return s.replace(/[\x00-\x1f\x7f]+/g, " ").replace(/::/g, ": :");
}

/**
 * The --problems file of scripts/check-piece-licenses.ts, which the catalog
 * sync pastes into its PR body (#1177 follow-up). A PR body holds 65536
 * characters and the verdict the sync wrote follows this section, so each
 * line is capped and so is their number: a tree with hundreds of denied
 * packages must not push the verdict off the end. Unicode line and paragraph
 * separators and bidi controls are dropped too, so a package name cannot
 * reorder or split what a reviewer reads.
 */
export const PROBLEMS_MAX_LINES = 50;
export const PROBLEMS_MAX_LINE_CHARS = 300;
export function problemsFileText(problems: readonly string[]): string {
  const clean = problems.map((p) => {
    const line = oneLine(p).replace(/[\u2028\u2029\u202a-\u202e\u2066-\u2069\u200e\u200f\u061c\ufeff]/g, "");
    return line.length > PROBLEMS_MAX_LINE_CHARS ? line.slice(0, PROBLEMS_MAX_LINE_CHARS - 3) + "..." : line;
  });
  const shown = clean.length > PROBLEMS_MAX_LINES ? clean.slice(0, PROBLEMS_MAX_LINES - 1) : clean;
  if (shown.length < clean.length) shown.push(`... and ${clean.length - shown.length} more problem(s); see the licenses job in the run`);
  return shown.map((line) => line + "\n").join("");
}

/** Scan an installed shared tree, and render its notices when it passes. */
export function checkSharedTreeLicenses(
  piecesDir: string,
  catalog: readonly CatalogEntry[],
  opts: {
    /**
     * Dev smoke only (`--pieces 0`): bun writes no bun.lock for an install
     * with no dependencies, so an EMPTY catalog may pass without one. Refused
     * for any non-empty catalog, so a real build can never skip the lock.
     */
    lockfile?: "required" | "if-present";
  } = {},
): SharedTreeLicenseCheck {
  if (opts.lockfile === "if-present" && catalog.length > 0) {
    throw new Error("the bun.lock requirement can only be relaxed for an empty catalog (--pieces 0)");
  }
  const scan = scanInstalledTree(piecesDir, {
    catalogPackages: new Set(catalog.map((e) => e.npmPackage)),
    // bun always writes one here; without it no identity can be checked.
    lockfile: opts.lockfile ?? "required",
  });
  const problems = describeViolations(scan).map(oneLine);
  // Completeness: every piece the tree was installed for must be in it, at
  // the top, under its own name. An empty or half-written tree, or a bun
  // layout this scan does not read, fails instead of passing as clean.
  const top = new Set(scan.packages.filter((p) => p.chain.length === 1).map((p) => p.name));
  for (const e of catalog) {
    if (!top.has(e.npmPackage)) problems.push(oneLine(`${e.npmPackage} was to be installed, but the scan did not find it at the top of the tree`));
  }
  const ok = problems.length === 0;
  const allowed = scan.packages.flatMap((p) => (p.verdict.allowed ? [{ p, v: p.verdict }] : []));
  const releases = (xs: string[]) => [...new Set(xs)];
  return {
    ok,
    problems,
    notices: ok
      ? renderNotices(piecesDir, scan, "Third-party notices: shared pieces tree", {
          activepiecesLicense: readFileSync(ACTIVEPIECES_LICENSE, "utf8"),
        })
      : null,
    unusedReviewed: scan.unusedReviewed,
    packages: releases(scan.packages.map((p) => `${p.name}@${p.version}`)).length,
    weakCopyleft: releases(allowed.filter(({ v }) => v.category === "weak-copyleft").map(({ p }) => oneLine(`${p.name}@${p.version} (${p.verdict.license})`))),
    reviewed: releases(allowed.filter(({ v }) => v.basis === "reviewed").map(({ p }) => `${p.name}@${p.version}`)),
    scan,
  };
}
