#!/usr/bin/env bun
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';

function containedFile(root: string, path: string) {
  const rel = relative(root, path);
  if (isAbsolute(rel) || rel.split(sep).includes('..')) throw new Error('Module escapes its owner');
  let current = root;
  for (const segment of ['', ...rel.split(sep)]) {
    current = join(current, segment);
    if (lstatSync(current).isSymbolicLink()) throw new Error('Symlink module path');
  }
  if (!lstatSync(path).isFile() || !realpathSync(path).startsWith(realpathSync(root) + sep)) throw new Error('Invalid module file');
}
export async function generateUIManifest(repo: string): Promise<string> {
  const { VIEWS, validManifest } = await import('../ui/src/onboarding-next/host/contract.ts');
  const entries: string[] = [], ids = new Set<string>(), capabilities = new Set<string>();
  for (const spec of VIEWS) {
    const folder = resolve(repo, 'ui/src/onboarding-next/views', spec.directory), path = join(folder, 'manifest.json');
    if (lstatSync(folder, { throwIfNoEntry: false })?.isSymbolicLink() || lstatSync(path, { throwIfNoEntry: false })?.isSymbolicLink()) throw new Error('Symlink module path');
    if (!existsSync(path)) continue;
    containedFile(resolve(repo), path);
    if (lstatSync(path).size > 4096) throw new Error('Oversized manifest');
    const manifest: unknown = JSON.parse(readFileSync(path, 'utf8'));
    if (!validManifest(manifest, spec) || ids.has(manifest.id) || manifest.provides.some(c => capabilities.has(c))) throw new Error(`Invalid manifest: ${spec.id}`);
    // View requirements are exclusively backend capabilities, so this graph
    // has no view-to-view edges and cannot contain cycles.
    ids.add(manifest.id); manifest.provides.forEach(c => capabilities.add(c));
    containedFile(folder, join(folder, 'index.tsx'));
    entries.push(`  { manifest: ${JSON.stringify(manifest)}, load: () => import(${JSON.stringify(`../../views/${spec.directory}/index.tsx`)}) },`);
  }
  return '// Generated by scripts/onboarding-next-ui-manifest.ts. Do not edit.\n'
    + 'import type { ViewModule } from "../contract.ts";\n'
    + `export const viewModules: readonly ViewModule[] = [\n${entries.join('\n')}\n];\n`;
}
export async function writeUIManifest(repo: string) {
  const text = await generateUIManifest(repo), path = resolve(repo, CATALOG_PATH);
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  const temp = `${path}.${process.pid}.tmp`; writeFileSync(temp, text); renameSync(temp, path);
}
export const CATALOG_PATH = 'ui/src/onboarding-next/host/generated/catalog.ts';
export async function catalogIsCurrent(repo: string): Promise<boolean> {
  const path = resolve(repo, CATALOG_PATH);
  return existsSync(path) && readFileSync(path, 'utf8') === await generateUIManifest(repo);
}
if (import.meta.main) {
  const repo = resolve(import.meta.dir, '..');
  if (process.argv.includes('--check')) {
    if (!await catalogIsCurrent(repo)) {
      console.error(`[onboarding-ui] ${CATALOG_PATH} is stale; run \`bun run generate:onboarding-ui\` and commit it.`);
      process.exit(1);
    }
  } else await writeUIManifest(repo);
}
