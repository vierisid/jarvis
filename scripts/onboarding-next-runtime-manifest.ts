#!/usr/bin/env bun
/** Build-time discovery only. Never imports or executes a discovered module. */
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

function containedFile(root: string, path: string): void {
  const rel = relative(root, path);
  if (rel.startsWith('..') || rel.startsWith('/')) throw new Error('Module path escapes its owner');
  let current = root;
  if (lstatSync(current).isSymbolicLink()) throw new Error('Symlink module root');
  for (const segment of rel.split('/')) {
    current = join(current, segment);
    if (lstatSync(current).isSymbolicLink()) throw new Error('Symlink module path');
  }
  if (!lstatSync(path).isFile() || !realpathSync(path).startsWith(realpathSync(root) + '/')) throw new Error('Invalid module file');
}
export function assertAcyclic(manifests: Array<{ provides: readonly string[]; requires: readonly string[] }>): void {
  const edges = new Map<string, readonly string[]>();
  for (const m of manifests) for (const c of m.provides) {
    if (edges.has(c)) throw new Error('Duplicate capability');
    edges.set(c, m.requires);
  }
  const visiting = new Set<string>(), done = new Set<string>();
  const visit = (c: string) => {
    if (visiting.has(c)) throw new Error('Cyclic provider requirements');
    if (done.has(c)) return;
    visiting.add(c);
    for (const dep of edges.get(c) ?? []) visit(dep);
    visiting.delete(c); done.add(c);
  };
  for (const c of edges.keys()) visit(c);
}
export async function generateRuntimeManifest(repo: string): Promise<string> {
  const { PROVIDERS } = await import('../src/onboarding-next/runtime/contract.ts');
  const root = resolve(repo, 'src/onboarding-next');
  const entries: string[] = [], manifests: Array<{ provides: string[]; requires: string[] }> = [];
  for (const spec of PROVIDERS) {
    const folder = join(root, spec.directory), path = join(folder, 'manifest.json');
    // lstat (unlike existsSync) observes dangling links too.
    if (lstatSync(folder, { throwIfNoEntry: false })?.isSymbolicLink()
      || lstatSync(path, { throwIfNoEntry: false })?.isSymbolicLink()) throw new Error('Symlink module path');
    if (!existsSync(path)) {
      continue;
    }
    containedFile(resolve(repo), path);
    if (lstatSync(path).size > 4096) throw new Error('Oversized manifest');
    const m = JSON.parse(readFileSync(path, 'utf8'));
    const same = (a: unknown, b: readonly string[]) => Array.isArray(a) && JSON.stringify(a) === JSON.stringify(b);
    if (!m || typeof m !== 'object' || Object.keys(m).sort().join(',') !== 'entry,id,kind,provides,requires,schemaVersion'
      || m.schemaVersion !== 1 || m.id !== spec.id || m.kind !== 'provider' || m.entry !== './index.ts'
      || !same(m.provides, [spec.capability]) || !same(m.requires, spec.requires)) throw new Error(`Invalid manifest for ${spec.id}`);
    const files = ['index.ts', ...('companions' in spec ? spec.companions : [])];
    for (const file of files) containedFile(resolve(repo), join(folder, file));
    manifests.push(m);
    const imports = files.map(f => `import(${JSON.stringify(`../../${spec.directory}/${f}`)})`);
    entries.push(`  { manifest: ${JSON.stringify(m)}, load: async () => Object.assign({}, ...await Promise.all([${imports.join(', ')}])) },`);
  }
  assertAcyclic(manifests);
  return '// Generated by scripts/onboarding-next-runtime-manifest.ts. Do not edit.\n'
    + 'import type { ModuleEntry } from "../contract.ts";\n'
    + `export const runtimeModules: readonly ModuleEntry[] = [\n${entries.join('\n')}\n];\n`;
}
export async function writeRuntimeManifest(repo: string): Promise<void> {
  const text = await generateRuntimeManifest(repo);
  const out = resolve(repo, 'src/onboarding-next/runtime/generated/catalog.ts');
  mkdirSync(dirname(out), { recursive: true });
  if (existsSync(out) && readFileSync(out, 'utf8') === text) return;
  const temp = `${out}.${process.pid}.tmp`;
  writeFileSync(temp, text); renameSync(temp, out);
}
if (import.meta.main) {
  const repo = resolve(import.meta.dir, '..');
  // Docker's dependency-only stage has scripts but no source. Its UI build
  // generates after COPY src; source installs and published packages do too.
  if (!process.argv.includes('--if-present') || existsSync(join(repo, 'src/onboarding-next/runtime/contract.ts'))) {
    await writeRuntimeManifest(repo);
  }
}
